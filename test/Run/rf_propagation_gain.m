% Antenna-gain stub on TxSite / RxSite — AntennaGain is a scalar dBi
% property (defaults to 0 dBi = isotropic).  Real pattern-based gain
% lookup waits for the wire-MoM solver (ANT-Tier-2).

tx = TxSite('Name', 'A', ...
            'Latitude', 42.3, 'Longitude', -71.35, ...
            'AntennaHeight', 30, ...
            'TransmitterFrequency', 2.5e9, ...
            'TransmitterPower', 1, ...
            'AntennaGain', 10);            % +10 dBi TX
rx = RxSite('Name', 'B', ...
            'Latitude', 42.35, 'Longitude', -71.10, ...
            'AntennaGain', 3);             % +3 dBi RX

pm = PropagationModel('freespace');
ss_dbm = sigstrength(rx, tx, pm);
disp(ss_dbm);
% Sanity: 1 W = 30 dBm.  At ~21.5 km / 2.5 GHz, FSPL ≈ 127.04 dB.
%        30 + 10 - 127.04 + 3 = -84.04 dBm.

% Coverage method also still runs.
coverage(tx, pm);
